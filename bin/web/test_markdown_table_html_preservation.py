# Test Case 1: Simple table with one image row
def test_simple_table_with_image_preserves_html():
    """
    Test that a simple markdown table with one image row produces unescaped HTML.
    
    This test will FAIL on unfixed code, demonstrating that HTML tags are being escaped.
    """
    markdown_input = """# Merchant Items

| Item | Price | Image |
|------|-------|-------|
| Sword | 10 gp | ![Sword](https://example.com/sword.jpg) |
"""
    
    result = markdown_to_html(markdown_input)
    
    # Expected behavior (after fix): HTML should be preserved, not escaped
    # On UNFIXED code, these assertions will FAIL because:
    # - HTML tags are escaped (e.g., &lt;button&gt; instead of <button>)
    # - HTML is wrapped in <p> tags
    
    # Verify button HTML is preserved (not escaped)
    assert '<button' in result, \
        "COUNTEREXAMPLE: <button tag is escaped or missing. HTML is not preserved."
    assert 'onclick=' in result, \
        "COUNTEREXAMPLE: onclick attribute is escaped or missing. HTML attributes are not preserved."
    assert 'Show Image' in result, \
        "COUNTEREXAMPLE: Button text is missing or escaped."
    
    # Verify img HTML is preserved (not escaped)
    assert '<img' in result, \
        "COUNTEREXAMPLE: <img tag is escaped or missing. Image HTML is not preserved."
    assert 'src="https://example.com/sword.jpg"' in result, \
        "COUNTEREXAMPLE: Image src attribute is escaped or missing."
    
    # Verify HTML is NOT wrapped in <p> tags (check for <p> tags INSIDE HTML elements)
    # The bug manifests as <p> tags wrapping content INSIDE buttons and breaking img attributes
    assert '</button>\n        <button' in result or '</button>\n<' in result, \
        "COUNTEREXAMPLE: Button structure appears malformed."
    
    # The actual bug: lines inside multi-line HTML elements get wrapped in <p> tags
    # This breaks the HTML structure by inserting <p> tags in the middle of elements
    button_section = result[result.find('<button'):result.find('</button>') + 9] if '<button' in result else ""
    assert '<p class="mb-3 text-gray-300">' not in button_section, \
        f"COUNTEREXAMPLE: <p> tags found INSIDE button element, breaking HTML structure. Button section: {button_section[:200]}"
    
    # Verify class attributes are preserved (not escaped)
    assert 'class="toggle-btn' in result, \
        "COUNTEREXAMPLE: CSS class attributes are escaped or missing."
    assert 'class="hidden max-w-xs' in result, \
        "COUNTEREXAMPLE: Image CSS classes are escaped or missing."


